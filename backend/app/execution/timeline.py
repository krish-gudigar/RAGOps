"""Turn a finished result into the step-by-step timeline shown in the UI."""

from app.models.domain import TaskExecutionResult

STRATEGY_LABELS = {
    "dynamic": "Dynamic routing",
    "always_small": "Always-small strategy",
    "always_strong": "Always-strong strategy",
}


def build_timeline(result: TaskExecutionResult) -> list[str]:
    a = result.analysis
    events = [
        "Task received",
        f"Task analyzed: {a.task_type}, score {a.total_score}/10 ({a.difficulty} difficulty)",
    ]
    first = result.attempts[0]
    label = STRATEGY_LABELS.get(result.strategy, result.strategy)
    events.append(f"{label}: {first.tier} model selected")

    for i, attempt in enumerate(result.attempts):
        events.append(f"Response generated by the {attempt.tier} model")
        if attempt.validation is None:
            events.append("Validation skipped (turned off)")
        elif attempt.validation.valid:
            events.append("Validation passed")
        else:
            events.append("Validation failed")
        if attempt.escalated and i + 1 < len(result.attempts):
            events.append(f"Escalated to the {result.attempts[i + 1].tier} model")

    events.append("Final response returned")
    return events